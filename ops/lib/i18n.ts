export type StringKey = keyof (typeof UI_STRINGS)["en"];

const COOKIE_NAME = "tg_locale";

export async function getLocale(): Promise<Locale> {
  const store = await cookies();
  const value = store.get(COOKIE_NAME)?.value;
  return value === "fr" ? "fr" : "en";
}

export function t(locale: Locale, key: StringKey, vars?: Record<string, string>): string {
  let str: string = UI_STRINGS[locale][key] ?? UI_STRINGS.en[key];
  if (vars) {
    for (const [k, v] of Object.entries(vars)) str = str.replaceAll(`{${k}}`, v);
  }
  return str;
}

// Falls back to the English field silently when no French translation exists yet — never an
// error, never a placeholder string, just the authoritative English text (same "honest absence"
// discipline research/09_BUSINESS_RULES.md found already governing the marketing site).
export function localized(locale: Locale, en: string, fr: string | null | undefined): string {
  if (locale === "fr" && fr) return fr;
  return en;
}

